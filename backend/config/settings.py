def env_bool(name, default):
    """Read a boolean environment value without treating "false" as true."""
    value = os.environ.get(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


IS_RENDER = bool(os.environ.get("RENDER") or os.environ.get("RENDER_EXTERNAL_HOSTNAME"))
# Keep local development convenient, but never enable Django debug mode on Render.
